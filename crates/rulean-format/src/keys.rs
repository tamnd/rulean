/// The number of known keys.
pub const COUNT: usize = 72;

/// The code of the key `k`, or `COUNT` if the format does not use the key.
pub fn code(k: &[u8]) -> usize {
    match k {
        b"meta" => META,
        b"in" => IN,
        b"il" => IL,
        b"ie" => IE,
        b"axiom" => AXIOM,
        b"def" => DEF,
        b"opaque" => OPAQUE,
        b"thm" => THM,
        b"quot" => QUOT,
        b"inductive" => INDUCTIVE,
        b"str" => STR,
        b"num" => NUM,
        b"succ" => SUCC,
        b"max" => MAX,
        b"imax" => IMAX,
        b"param" => PARAM,
        b"bvar" => BVAR,
        b"sort" => SORT,
        b"const" => CONST,
        b"app" => APP,
        b"lam" => LAM,
        b"forallE" => FORALL_E,
        b"letE" => LET_E,
        b"proj" => PROJ,
        b"natVal" => NAT_VAL,
        b"strVal" => STR_VAL,
        b"mdata" => MDATA,
        b"pre" => PRE,
        b"i" => I,
        b"name" => NAME,
        b"us" => US,
        b"fn" => FN,
        b"arg" => ARG,
        b"binderInfo" => BINDER_INFO,
        b"body" => BODY,
        b"type" => TYPE,
        b"nondep" => NONDEP,
        b"value" => VALUE,
        b"idx" => IDX,
        b"struct" => STRUCT,
        b"typeName" => TYPE_NAME,
        b"expr" => EXPR,
        b"data" => DATA,
        b"all" => ALL,
        b"hints" => HINTS,
        b"isUnsafe" => IS_UNSAFE,
        b"levelParams" => LEVEL_PARAMS,
        b"safety" => SAFETY,
        b"kind" => KIND,
        b"regular" => REGULAR,
        b"types" => TYPES,
        b"ctors" => CTORS,
        b"recs" => RECS,
        b"isRec" => IS_REC,
        b"isReflexive" => IS_REFLEXIVE,
        b"numIndices" => NUM_INDICES,
        b"numNested" => NUM_NESTED,
        b"numParams" => NUM_PARAMS,
        b"cidx" => CIDX,
        b"induct" => INDUCT,
        b"numFields" => NUM_FIELDS,
        b"k" => K,
        b"numMinors" => NUM_MINORS,
        b"numMotives" => NUM_MOTIVES,
        b"rules" => RULES,
        b"ctor" => CTOR,
        b"nfields" => NFIELDS,
        b"rhs" => RHS,
        b"exporter" => EXPORTER,
        b"lean" => LEAN,
        b"format" => FORMAT,
        b"version" => VERSION,
        _ => COUNT,
    }
}
